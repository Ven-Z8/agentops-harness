def test_api_can_create_edit_mode_run(tmp_path: Path, monkeypatch) -> None:
    monkeypatch.setattr("app.api.settings.llm_provider", "mock")
    repo_path = tmp_path / "repo"
    repo_path.mkdir()
    (repo_path / "app.py").write_text("print('hello')\n")
    subprocess.run(["git", "init"], cwd=repo_path, check=True, capture_output=True)
    subprocess.run(["git", "config", "user.email", "test@example.com"], cwd=repo_path, check=True)
    subprocess.run(["git", "config", "user.name", "Test User"], cwd=repo_path, check=True)
    subprocess.run(["git", "add", "."], cwd=repo_path, check=True)
    subprocess.run(
        ["git", "commit", "-m", "initial"],
        cwd=repo_path,
        check=True,
        capture_output=True,
    )
    worker_path = tmp_path / "worker.py"
    worker_path.write_text(
        "from pathlib import Path\n"
        "Path('marker.txt').write_text('created\\n')\n"
        "print('api worker complete')\n"
    )
    client = TestClient(create_api(storage_path=tmp_path / "runs.db"))

    response = client.post(
        "/runs",
        json={
            "repo_path": str(repo_path),
            "task": "Create marker",
            "worker_command": f"{sys.executable} {worker_path}",
            "test_commands": [],
        },
    )

    assert response.status_code == 201
    run_response = client.get(f"/runs/{response.json()['run_id']}")
    payload = run_response.json()
    assert payload["edit_result"]["status"] == "completed"
    assert "marker.txt" in payload["changed_files"]
